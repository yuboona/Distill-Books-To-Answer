_T2S: dict[str, str] = {}
for token in _PAIRS.split():
    if len(token) == 2 and token[0] != token[1]:
        _T2S[token[0]] = token[1]


def to_simplified(text: str) -> str:
    return "".join(_T2S.get(ch, ch) for ch in text)


def fold_for_match(text: str) -> str:
    """Lowercase Latin + trad→simp. Scoring only; do not cite this string."""
    return to_simplified(text).lower()


def both_script_forms(term: str) -> list[str]:
    """Original + simplified fold (deduped)."""
    folded = fold_for_match(term)
    out = []
    for x in (term, folded, to_simplified(term)):
        if x and x not in out:
            out.append(x)
    return out
